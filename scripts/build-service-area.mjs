/**
 * Rebuild the service-area bitsets from the eligible-ZIP CSV and the
 * Census ZCTA gazetteer.
 *
 *   node scripts/build-service-area.mjs
 *   node scripts/build-service-area.mjs --gazetteer /path/to/2025_Gaz_zcta_national.txt
 *
 * The gazetteer is downloaded from the Census Bureau when --gazetteer is omitted.
 * Writes src/serviceAreaData.ts and public/shopper/serviceAreaData.js.
 */
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = path.join(root, "data/service-area/eligible_zips_10mi.csv");
const gazetteerUrl =
  "https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_zcta_national.zip";

function argValue(flag) {
  const index = process.argv.indexOf(flag);
  if (index < 0) return "";
  return process.argv[index + 1] || "";
}

function readEligibleZips() {
  const text = readFileSync(csvPath, "utf8");
  const zips = new Set();
  const lines = text.split(/\r?\n/);
  const header = (lines[0] || "").split(",");
  const zipColumn = header.indexOf("zip");
  if (zipColumn < 0) throw new Error("eligible CSV is missing a zip column");
  for (const line of lines.slice(1)) {
    if (!line.trim()) continue;
    const zip = line.split(",")[zipColumn]?.trim();
    if (!/^\d{5}$/.test(zip || "")) throw new Error(`Bad ZIP in eligible CSV: ${zip}`);
    zips.add(zip);
  }
  return zips;
}

function gazetteerText() {
  const given = argValue("--gazetteer");
  if (given) return readFileSync(given, "utf8");
  const dir = mkdtempSync(path.join(tmpdir(), "zcta-"));
  const zipPath = path.join(dir, "gaz.zip");
  execFileSync("curl", ["-fsSL", "-o", zipPath, gazetteerUrl], { stdio: "inherit" });
  return execFileSync("unzip", ["-p", zipPath], { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });
}

function readZctas(text) {
  const zips = new Set();
  const lines = text.split(/\r?\n/);
  const header = (lines[0] || "").split("|");
  const column = header.indexOf("GEOID");
  if (column < 0) throw new Error("Gazetteer is missing a GEOID column");
  for (const line of lines.slice(1)) {
    if (!line.trim()) continue;
    const zip = line.split("|")[column]?.trim();
    if (!/^\d{5}$/.test(zip || "")) continue;
    zips.add(zip);
  }
  return zips;
}

function bitset(zips) {
  const bytes = Buffer.alloc(Math.ceil(100000 / 8));
  for (const zip of zips) {
    const n = Number(zip);
    bytes[n >> 3] |= 1 << (n & 7);
  }
  return bytes.toString("base64");
}

const eligible = readEligibleZips();
const zcta = readZctas(gazetteerText());
if (eligible.size !== 6443) {
  throw new Error(`Expected 6443 eligible ZIPs, found ${eligible.size}`);
}
let eligibleZcta = 0;
for (const zip of eligible) {
  if (!zcta.has(zip)) throw new Error(`Eligible ZIP ${zip} is not a Census ZCTA`);
  eligibleZcta += 1;
}
if (eligibleZcta !== eligible.size) throw new Error("Eligible ZIP check failed");

const payload = {
  eligibleBits: bitset(eligible),
  zctaBits: bitset(zcta),
  eligibleCount: eligible.size,
  zctaCount: zcta.size,
};

const banner = "/* Generated by scripts/build-service-area.mjs. Do not edit. */\n";
const ts = `${banner}export const eligibleBits = ${JSON.stringify(payload.eligibleBits)};
export const zctaBits = ${JSON.stringify(payload.zctaBits)};
export const eligibleCount = ${payload.eligibleCount};
export const zctaCount = ${payload.zctaCount};
`;
const js = `${banner}export const eligibleBits = ${JSON.stringify(payload.eligibleBits)};
export const zctaBits = ${JSON.stringify(payload.zctaBits)};
export const eligibleCount = ${payload.eligibleCount};
export const zctaCount = ${payload.zctaCount};
`;

writeFileSync(path.join(root, "src/serviceAreaData.ts"), ts);
writeFileSync(path.join(root, "public/shopper/serviceAreaData.js"), js);
console.log(`eligible ${payload.eligibleCount}, zcta ${payload.zctaCount}`);
